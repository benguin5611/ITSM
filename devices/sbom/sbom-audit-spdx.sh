	local syft_errors="${SBOM_DIR}/syft-errors-${TIMESTAMP}.log"
	local syft_timeout=1800
	local partial_sboms=()
	local scan_idx=0

	for scan_path in "${scan_paths[@]}"; do
		echo "  → Scanning: $scan_path"
		local partial_file="${temp_file}.${scan_idx}"
		scan_idx=$((scan_idx + 1))

		# Retry loop: Syft's directory indexer treats ENOENT as fatal when transient
		# directories vanish mid-scan (anchore/syft#3286). Retry up to 3 times.
		local syft_max_retries=3
		local syft_attempt=0
		local syft_exit=1

		while [ "$syft_attempt" -lt "$syft_max_retries" ]; do
			syft_attempt=$((syft_attempt + 1))
			rm -f "$partial_file" "$syft_errors"

			if [ "$syft_attempt" -gt 1 ]; then
				echo "    → Retry $syft_attempt/$syft_max_retries..."
			fi

			SYFT_CHECK_FOR_APP_UPDATE=false taskpolicy -b syft scan "dir:$scan_path" \
				--source-name "$DEVICE_ID" \
				--source-version "$TIMESTAMP" \
				--output "spdx-json=$partial_file" \
				--exclude '**/.git/**' 2>"$syft_errors" &
			local syft_pid=$!
			(sleep "$syft_timeout" && kill "$syft_pid" 2>/dev/null) &
			local watchdog_pid=$!
			wait "$syft_pid" 2>/dev/null
			syft_exit=$?
			kill "$watchdog_pid" 2>/dev/null || true
			wait "$watchdog_pid" 2>/dev/null || true

			if [ "$syft_exit" -eq 0 ]; then
				break
			fi

			# Timeout — not retryable
			if ! kill -0 "$syft_pid" 2>/dev/null && [ "$syft_exit" -gt 128 ]; then
				echo "    ⚠ Syft scan timed out for $scan_path (skipping)" >&2
				break
			fi

			# Transient indexing error — retryable
			if [ -f "$syft_errors" ] && grep -q "no such file or directory" "$syft_errors" 2>/dev/null; then
				echo "    ⚠ Transient path error (attempt $syft_attempt/$syft_max_retries)" >&2
				continue
			fi

			# Non-transient failure
			echo "    ⚠ Syft scan failed for $scan_path (exit $syft_exit, skipping)" >&2
			if [ -f "$syft_errors" ] && [ -s "$syft_errors" ]; then
				tail -5 "$syft_errors" >&2
			fi
			break
		done

		rm -f "$syft_errors"

		if [ "$syft_exit" -eq 0 ] && [ -f "$partial_file" ] && [ -s "$partial_file" ]; then
			partial_sboms+=("$partial_file")
			local partial_pkg_count
			partial_pkg_count=$(jq '.packages | length' "$partial_file" 2>/dev/null || echo "?")
			echo "    ✓ $partial_pkg_count packages"
		else
			rm -f "$partial_file"
		fi
	done

	if [ ${#partial_sboms[@]} -eq 0 ]; then
		echo "✗ All Syft scans failed — no system packages found" >&2
		return 1
	fi

	# Merge partial SBOMs and clean SPDX output
	# - Remove files[] (too large)
	# - Deduplicate packages and hasExtractedLicensingInfos
	# - Remove file-dependent fields incompatible with filesAnalyzed=false
	# - Remove empty versionInfo fields
	# - Remove CPE externalRefs (cpe23Type)
	if ! jq -s '
        {
            SPDXID: .[0].SPDXID,
            spdxVersion: .[0].spdxVersion,
            creationInfo: .[0].creationInfo,
            name: .[0].name,
            dataLicense: .[0].dataLicense,
            documentNamespace: .[0].documentNamespace,
            hasExtractedLicensingInfos: (
                [.[].hasExtractedLicensingInfos[]?] |
                group_by(.licenseId) | map(.[0])
            ),
            packages: (
                [.[].packages[]?] |
                unique_by(.SPDXID // (.name + "-" + (.versionInfo // "UNKNOWN") + "-" + (.downloadLocation // "UNKNOWN"))) |
                map(
                    .filesAnalyzed = false |
                    del(.licenseInfoFromFiles, .packageVerificationCode, .hasFiles) |
                    if .versionInfo == "" then del(.versionInfo) else . end |
                    if .externalRefs then
                        .externalRefs |= map(select(.referenceType != "cpe23Type"))
                    else . end |
                    if .externalRefs == [] then del(.externalRefs) else . end
                )
            )
        } |
        del(.files) |
        if .hasExtractedLicensingInfos == [] then del(.hasExtractedLicensingInfos) else . end
    ' "${partial_sboms[@]}" >"$output_file"; then
		for f in "${partial_sboms[@]}"; do rm -f "$f"; done
		echo "  ✗ jq merge/processing failed for system SBOM" >&2
		return 1
	fi

	# Clean up partial files
	for f in "${partial_sboms[@]}"; do rm -f "$f"; done

	if [ ! -s "$output_file" ]; then
		echo "  ✗ jq produced empty output for system SBOM" >&2
		return 1
	fi

	local pkg_count
	pkg_count=$(jq '.packages | length' "$output_file" 2>/dev/null || echo "0")
	echo "  ✓ System scan complete: $pkg_count packages"

	if [[ "$MODE" == test* ]]; then
		echo "  ✓ Saved to: $output_file"
	fi

	return 0
}

generate_device_sbom() {
	local nix_sbom="${SBOM_DIR}/nix-${TIMESTAMP}.spdx.json"
	local system_sbom="${SBOM_DIR}/system-${TIMESTAMP}.spdx.json"
	local merged_sbom="${SBOM_DIR}/device-${DEVICE_ID}-${TIMESTAMP}.spdx.json"

	local sboms_to_merge=()

	# Generate Nix SBOM (required)
	if ! generate_nix_sbom "$nix_sbom" >&2; then
		echo "✗ Nix SBOM generation failed" >&2
		exit 1
	fi
	sboms_to_merge+=("$nix_sbom")

	# Generate system SBOM (required)
	if ! generate_system_sbom "$system_sbom" >&2; then
		echo "✗ System scan failed" >&2
		exit 1
	fi
	sboms_to_merge+=("$system_sbom")

	# Merge all SBOMs
	echo "" >&2
	echo "→ Merging SBOMs..." >&2

	if [ ${#sboms_to_merge[@]} -eq 1 ]; then
		# Only one SBOM, just copy it
		cp "${sboms_to_merge[0]}" "$merged_sbom"
		echo "  ✓ Single SBOM copied to final location" >&2
	else
		# Merge multiple SBOMs
		# Generate unique namespace for this document
		local doc_uuid
		if command -v uuidgen &>/dev/null; then
			doc_uuid=$(uuidgen | tr '[:upper:]' '[:lower:]')
		else
			# Fallback for the (unlikely) case uuidgen isn't on PATH.
			# documentNamespace is non-security-critical, so a deterministic
			# fallback is sufficient. `/proc/sys/kernel/random/uuid` is
			# Linux-only; this script runs on macOS, so we go straight to
			# the timestamp/pid fallback.
			doc_uuid="$(date -u +%Y%m%d%H%M%S)-$$-$RANDOM"
		fi
		local doc_namespace="http://spdx.org/spdxdocs/${DEVICE_ID}-${doc_uuid}"

		if ! jq -s --arg device_id "$DEVICE_ID" --arg namespace "$doc_namespace" '{
                SPDXID: "SPDXRef-DOCUMENT",
                spdxVersion: "SPDX-2.3",
                creationInfo: {
                    created: (now | strftime("%Y-%m-%dT%H:%M:%SZ")),
                    creators: ["Tool: sbom-audit-spdx"]
                },
                name: $device_id,
                dataLicense: "CC0-1.0",
                documentNamespace: $namespace,
                hasExtractedLicensingInfos: (
                    [.[].hasExtractedLicensingInfos[]?] |
                    group_by(.licenseId) | map(.[0])
                ),
                packages: ([.[].packages[]?] | unique_by(.SPDXID // (.name + "-" + (.versionInfo // "UNKNOWN") + "-" + (.downloadLocation // "UNKNOWN"))) |
                           map(
                               .filesAnalyzed = false |
                               del(.licenseInfoFromFiles, .packageVerificationCode, .hasFiles) |
                               if .versionInfo == "" then del(.versionInfo) else . end |
                               if .externalRefs then
                                   .externalRefs |= map(select(.referenceType != "cpe23Type"))
                               else . end |
                               if .externalRefs == [] then del(.externalRefs) else . end
                           )),
                relationships: [
                    {
                        spdxElementId: "SPDXRef-DOCUMENT",
                        relationshipType: "DESCRIBES",
                        relatedSpdxElement: (([.[].packages[]?] | unique_by(.SPDXID // (.name + "-" + (.versionInfo // "UNKNOWN") + "-" + (.downloadLocation // "UNKNOWN"))))[0].SPDXID // "NOASSERTION")
                    }
                ]
            } | if .hasExtractedLicensingInfos == [] then del(.hasExtractedLicensingInfos) else . end
        ' "${sboms_to_merge[@]}" >"$merged_sbom"; then
			echo "  ✗ jq merge failed for device SBOM" >&2
			exit 1
		fi

		if [ ! -s "$merged_sbom" ]; then
			echo "  ✗ jq produced empty output for device SBOM" >&2
			exit 1
		fi

		echo "  ✓ Merged ${#sboms_to_merge[@]} SBOMs" >&2
	fi

	local final_pkg_count
	final_pkg_count=$(jq '.packages | length' "$merged_sbom")
	echo "  ✓ Final SBOM: $final_pkg_count packages" >&2

	if [[ "$MODE" == test* ]]; then
		echo "  ✓ Saved to: $merged_sbom" >&2
	fi

	echo "$merged_sbom"
}

upload_sbom() {
	local sbom_file="$1"

	echo "→ Uploading SBOM..."

	# Calculate checksum
	local checksum
	checksum=$(shasum -a 256 "$sbom_file" | awk '{print $1}')

	# Build JSON payload safely using jq
	local json_payload
	json_payload=$(jq -n \
		--arg dev "$DEVICE_ID" \
		--arg sum "$checksum" \
		'{device_id: $dev, checksum: $sum}')

	# Pass auth token via --config file to keep it out of the process argument list
	local auth_config
	auth_config=$(mktemp)
	chmod 600 "$auth_config"
	printf 'header = "Authorization: %s"\n' "$SBOM_AUTH_TOKEN" >"$auth_config"

	# Request presigned URL from Lambda. Not retried: each presign mints
	# a fresh correlation_id + S3 key, so a transparent curl retry would
	# leak orphan presigns into logs/metrics without observable benefit.
	local presign_response
	presign_response=$(curl -sS -X POST "$LAMBDA_URL" \
		--max-time 60 \
		--connect-timeout 10 \
		--config "$auth_config" \
		-H "Content-Type: application/json" \
		-H "X-Device-ID: $DEVICE_ID" \
		-d "$json_payload") || {
		rm -f "$auth_config"
		echo "✗ Failed to request presigned URL" >&2
		return 1
	}
	rm -f "$auth_config"

	# Extract upload URL and correlation ID
	local upload_url correlation_id
	upload_url=$(echo "$presign_response" | jq -r '.upload_url')
	correlation_id=$(echo "$presign_response" | jq -r '.correlation_id // "unknown"')
	
	# Calculate HMAC signature using the same logic as the Go presignSignature function
	local sig
	if [ -z "$SBOM_PRESIGN_SECRET" ]; then
		echo "✗ SBOM_PRESIGN_SECRET environment variable not set" >&2
		return 1
	fi
	if command -v openssl &>/dev/null; then
		sig=$(printf '%s' "$checksum" | openssl dgst -sha256 -hmac "$SBOM_PRESIGN_SECRET" -hex | sed 's/^.* //')
	else
		echo "✗ openssl not available for HMAC signature calculation" >&2
		return 1
	fi

	if [ -z "$upload_url" ] || [ "$upload_url" = "null" ]; then
		echo "✗ Lambda returned invalid presigned URL response" >&2
		echo "  HTTP request succeeded but response did not contain upload_url" >&2
		return 1
	fi

	# Validate upload URL points to AWS S3 (prevent exfiltration via compromised Lambda)
	# Extract host from URL — only matches https://, so http:// is implicitly rejected
	local upload_host
	upload_host=$(printf '%s' "$upload_url" | sed -n 's|^https://\([^/]*\)/.*|\1|p')
	if [[ -z "$upload_host" || "$upload_host" != *.amazonaws.com ]]; then
		echo "✗ Presigned URL is not a valid HTTPS AWS endpoint" >&2
		return 1
	fi

	# Upload SBOM to S3 using presigned URL (with retry logic for transient failures)
	# IMPORTANT: Must include metadata headers matching presigned request
	# Use -w to capture HTTP status code, -o to suppress body output
	local http_code
	http_code=$(curl -sS -w '%{http_code}' -o /dev/null \
		--max-time 300 \
		--connect-timeout 10 \
		--retry 3 \
		--retry-delay 2 \
		-X PUT "$upload_url" \
		-H "Content-Type: application/json" \
		-H "x-amz-meta-device-id: $DEVICE_ID" \
		-H "x-amz-meta-checksum: $checksum" \
		-H "x-amz-meta-correlation-id: $correlation_id" \
		-H "x-amz-meta-sig: $sig" \
		-H "x-amz-server-side-encryption: AES256" \
		--data-binary "@$sbom_file") || {
		echo "✗ Upload request failed" >&2
		return 1
	}

	# Check HTTP status code (200-299 = success)
	if [ "$http_code" -lt 200 ] || [ "$http_code" -ge 300 ]; then
		echo "✗ Upload failed with HTTP $http_code" >&2
		return 1
	fi

	echo "✓ SBOM uploaded successfully"
	echo "  Device: $DEVICE_ID"
	echo "  Size: $(du -h "$sbom_file" | awk '{print $1}')"
	echo "  Checksum: ${checksum:0:16}..."
	echo "  Correlation ID: $correlation_id"
	echo "  HTTP Status: $http_code"

	return 0
}

cleanup_old_files() {
	if [[ "$MODE" == test* ]]; then
		# Skip cleanup in test mode
		return 0
	fi

	# Strict guardrails: Verify SBOM_DIR is set and is our directory
	if [ -z "$SBOM_DIR" ] || [ ! -d "$SBOM_DIR" ]; then
		echo "✗ SAFETY: SBOM_DIR not set or doesn't exist" >&2
		return 1
	fi

	# Verify SBOM_DIR is ~/.sbom-audit (production) or in TMPDIR (should never happen in production)
	if [[ "$SBOM_DIR" != "${HOME}/.sbom-audit" ]]; then
		echo "✗ SAFETY: SBOM_DIR is not ~/.sbom-audit: $SBOM_DIR" >&2
		return 1
	fi

	# Remove marker files older than 60 days (keep last 2 months)
	local old_markers
	old_markers=$(find "$SBOM_DIR" -maxdepth 1 -name ".last-upload-*" -type f -mtime +60 2>/dev/null | wc -l | tr -d ' ')

	# Remove stale SBOM files older than 1 day (should be uploaded or failed)
	local stale_sboms
	stale_sboms=$(find "$SBOM_DIR" -maxdepth 1 -name "*.spdx.json" -type f -mtime +1 2>/dev/null | wc -l | tr -d ' ')

	# Count intermediate files to clean
	local intermediate_files
	intermediate_files=$(find "$SBOM_DIR" -maxdepth 1 -type f \( -name "nix-*.spdx.json" -o -name "system-*.spdx.json" -o -name "device-*.spdx.json" \) 2>/dev/null | wc -l | tr -d ' ')

	if [ "$old_markers" -gt 0 ] || [ "$stale_sboms" -gt 0 ] || [ "$intermediate_files" -gt 0 ]; then
		echo "→ Cleaning up old files..."
	fi

	# Execute cleanup with maxdepth=1 (never recurse)
	if [ "$old_markers" -gt 0 ]; then
		find "$SBOM_DIR" -maxdepth 1 -name ".last-upload-*" -type f -mtime +60 -print -delete 2>/dev/null || true
		echo "  ✓ Removed $old_markers old marker file(s)"
	fi

	if [ "$stale_sboms" -gt 0 ]; then
		find "$SBOM_DIR" -maxdepth 1 -name "*.spdx.json" -type f -mtime +1 -print -delete 2>/dev/null || true
		echo "  ✓ Removed $stale_sboms stale SBOM file(s)"
	fi

	# Remove intermediate files (nix-*.spdx.json, system-*.spdx.json, device-*.spdx.json)
	if [ "$intermediate_files" -gt 0 ]; then
		find "$SBOM_DIR" -maxdepth 1 -type f \( -name "nix-*.spdx.json" -o -name "system-*.spdx.json" -o -name "device-*.spdx.json" \) -print -delete 2>/dev/null || true
		echo "  ✓ Removed $intermediate_files intermediate file(s)"
	fi

	if [ "$old_markers" -eq 0 ] && [ "$stale_sboms" -eq 0 ] && [ "$intermediate_files" -eq 0 ]; then
		echo "  ✓ No old files to clean"
	fi
}

test_mode_summary() {
	local sbom_file="$1"

	if [ ! -f "$sbom_file" ]; then
		echo "✗ SBOM file not found: $sbom_file" >&2
		return 1
	fi

	echo ""
	echo "=== Test Complete ==="
	echo ""
	echo "Final SBOM (single file with all packages):"
	echo "  Path: $sbom_file"
	echo "  Size: $(du -h "$sbom_file" 2>/dev/null | awk '{print $1}')"
	echo ""
	echo "SBOM validation:"

	# Validate SPDX fields
	local spdx_id spdx_version doc_namespace pkg_count
	spdx_id=$(jq -r '.SPDXID' "$sbom_file" 2>/dev/null)
	spdx_version=$(jq -r '.spdxVersion' "$sbom_file" 2>/dev/null)
	doc_namespace=$(jq -r '.documentNamespace' "$sbom_file" 2>/dev/null)
	pkg_count=$(jq '.packages | length' "$sbom_file" 2>/dev/null)

	echo "  SPDXID: $spdx_id"
	echo "  spdxVersion: $spdx_version"
	echo "  documentNamespace: $doc_namespace"
	echo "  packages: $pkg_count"
	echo ""

	# Show sample packages
	echo "Sample packages (first 5):"
	jq -r '.packages[0:5] | .[] | "  - \(.name) \(.versionInfo // "UNKNOWN")"' "$sbom_file" 2>/dev/null
	echo ""

	echo "✓ Single merged SBOM file created (intermediate files cleaned up)"
}

main() {
	# Validate Lambda URL configuration (required for production and test-upload modes)
	if [ "$MODE" != "test" ]; then
		if [ -z "$LAMBDA_URL" ]; then
			echo "✗ SBOM_LAMBDA_URL environment variable not set" >&2
			echo "  Configure in MDM custom-script environment variables" >&2
			echo "  Example: SBOM_LAMBDA_URL='https://abc123.lambda-url.us-east-1.on.aws/'" >&2
			exit 1
		fi
	fi

	# Validate authentication token (only required for production mode)
	# Test mode bypasses auth checks - no token needed
	if [ "$MODE" != "test" ]; then
		if [ -z "${SBOM_AUTH_TOKEN:-}" ]; then
			echo "✗ SBOM_AUTH_TOKEN environment variable not set" >&2
			echo "  This should be configured via MDM" >&2
			echo "  Use --test mode for local testing without token" >&2
			exit 1
		fi
		# Basic format check (expect 32+ printable chars)
		if [ ${#SBOM_AUTH_TOKEN} -lt 32 ]; then
			echo "⚠ Warning: SBOM_AUTH_TOKEN seems too short (${#SBOM_AUTH_TOKEN} chars, expected 32+)" >&2
			echo "  Continuing anyway - Lambda will reject if invalid" >&2
		fi
	fi

	# Acquire lockfile to prevent concurrent runs (macOS compatible)
	LOCKFILE="${SBOM_DIR}/.sbom.lock"
	# shellcheck disable=SC2174
	mkdir -p -m 700 "$SBOM_DIR"

	# Try to create lockfile exclusively (fails if exists)
	if ! (
		set -o noclobber
		echo $$ >"$LOCKFILE"
	) 2>/dev/null; then
		# Check if process is still running
		if [ -f "$LOCKFILE" ]; then
			local lock_pid
			lock_pid=$(cat "$LOCKFILE" 2>/dev/null)
			if [ -n "$lock_pid" ] && kill -0 "$lock_pid" 2>/dev/null; then
				# Check lock file age - if > 4 hours, assume stale even if PID alive
				local lock_age=0
				if command -v stat &>/dev/null; then
					if [[ "$(uname)" == "Darwin" ]]; then
						lock_age=$(($(date +%s) - $(stat -f %m "$LOCKFILE" 2>/dev/null || echo 0)))
					else
						lock_age=$(($(date +%s) - $(stat -c %Y "$LOCKFILE" 2>/dev/null || echo 0)))
					fi
				fi
				if [ "$lock_age" -gt 14400 ]; then
					echo "⚠ Removing stale lock (age: ${lock_age}s, PID: $lock_pid still alive but lock too old)" >&2
					rm -f "$LOCKFILE"
					if ! (
						set -o noclobber
						echo $$ >"$LOCKFILE"
					) 2>/dev/null; then
						echo "✗ Lock acquired by another process during stale cleanup; exiting" >&2
						exit 1
					fi
				else
					echo "✗ Another sbom-audit-spdx process is running (PID: $lock_pid); exiting" >&2
					exit 1
				fi
			else
				# Stale lockfile, remove and recreate with noclobber to prevent race
				rm -f "$LOCKFILE"
				if ! (
					set -o noclobber
					echo $$ >"$LOCKFILE"
				) 2>/dev/null; then
					echo "✗ Lock acquired by another process during stale cleanup; exiting" >&2
					exit 1
				fi
			fi
		else
			# Lockfile creation failed but file doesn't exist - filesystem issue
			echo "✗ Failed to create lockfile at $LOCKFILE (directory not writable?)" >&2
			exit 1
		fi
	fi

	# Clean up lockfile on exit and signals
	trap 'rm -f "$LOCKFILE"' EXIT INT TERM

	if [[ "$MODE" == test* ]]; then
		echo "=== SPDX SBOM Generation Test ==="
		echo "Output directory: $SBOM_DIR"
		echo ""
		echo "Checking dependencies..."
	fi

	# Distribute load to prevent thundering herd (production mode only)
	if [[ "$MODE" != test* ]] && [ -z "${SBOM_SKIP_DELAY:-}" ]; then
		local random_delay=$((RANDOM % 3600))
		echo "→ Waiting ${random_delay}s to distribute server load..."
		sleep "$random_delay"
	fi

	check_already_run

	# Clean up old files from previous runs
	cleanup_old_files

	ensure_homebrew || {
		echo "✗ Homebrew/Workbrew required but could not be installed" >&2
		echo "  Install manually: https://brew.sh or https://workbrew.com" >&2
		exit 1
	}
	ensure_jq || {
		echo "✗ jq is required but could not be installed" >&2
		exit 1
	}
	ensure_gnumfmt || true # Try to install, fall back to basic formatting if fails
	ensure_syft || {
		echo "✗ Syft is required but could not be installed" >&2
		exit 1
	}
	ensure_sbomnix || {
		echo "✗ sbomnix is required but could not be installed" >&2
		exit 1
	}
	ensure_pyspdxtools || {
		echo "✗ pyspdxtools is required for SPDX validation" >&2
		exit 1
	}

	if [[ "$MODE" == test* ]]; then
		echo ""
	fi

	local sbom_file
	sbom_file=$(generate_device_sbom) || exit 1

	# Validate SPDX document before upload/output
	echo ""
	validate_spdx "$sbom_file" || {
		echo "✗ SPDX validation failed - generated file may be invalid" >&2
		exit 1
	}

	if [[ "$MODE" == test* ]]; then
		# Clean up intermediate files in test mode too (with strict guardrails)
		if [ -n "$SBOM_DIR" ] && [ -d "$SBOM_DIR" ]; then
			find "$SBOM_DIR" -maxdepth 1 -type f \( \
				-name "nix-*.spdx.json*" -o \
				-name "system-*.spdx.json*" -o \
				-name "nix-pkg-*.spdx.json*" \
				\) ! -name "$(basename "$sbom_file")" -delete 2>/dev/null || true

			# Clean up sbomnix artifacts
			safe_delete_file "${SBOM_DIR}/sbom.cdx.json"
			safe_delete_file "${SBOM_DIR}/sbom.csv"
			safe_delete_file "${SBOM_DIR}/http_cache.sqlite"
		fi

		test_mode_summary "$sbom_file"

		# --test-upload: also upload to Lambda after showing test summary
		if [ "$MODE" = "test-upload" ]; then
			echo ""
			upload_sbom "$sbom_file" || exit 1
		fi
	else
		upload_sbom "$sbom_file" || exit 1

		# Mark as completed for this month (month-only format)
		local current_month
		current_month=$(date -u +%Y-%m)
		local marker_file="${SBOM_DIR}/.last-upload-${current_month}"
		if ! date -u +%Y-%m-%dT%H:%M:%SZ >"$marker_file" 2>/dev/null; then
			echo "⚠ Warning: Upload succeeded but monthly marker creation failed" >&2
			echo "  Next run may re-upload this month" >&2
			echo "  Marker path: $marker_file" >&2
		fi

		# Clean up SBOM file immediately after successful upload
		if [ -f "$sbom_file" ]; then
			safe_delete_file "$sbom_file"
			echo "✓ Cleaned up generated SBOM file"
		fi

		# Final cleanup of any remaining intermediate files (with strict guardrails)
		if [ -n "$SBOM_DIR" ] && [ -d "$SBOM_DIR" ] && [[ "$SBOM_DIR" == "${HOME}/.sbom-audit" ]]; then
			# Only delete our specific file patterns in our directory, never recurse
			find "$SBOM_DIR" -maxdepth 1 -type f \( \
				-name "nix-*.spdx.json" -o \
				-name "system-*.spdx.json" -o \
				-name "device-*.spdx.json" \
				\) -delete 2>/dev/null || true

			# Clean up sbomnix artifacts
			safe_delete_file "${SBOM_DIR}/sbom.cdx.json"
			safe_delete_file "${SBOM_DIR}/sbom.csv"
			safe_delete_file "${SBOM_DIR}/http_cache.sqlite"

			echo "✓ Cleaned up intermediate files"
		fi

		echo ""
		echo "=== SBOM Audit Complete ==="
	fi
}

main "$@"
