	exit 0
fi

# Validate flag combinations
if [[ "$MODE" == test* ]] && [ "$FORCE_RUN" = "true" ]; then
	echo "✗ Cannot use --test/--test-upload and --force together" >&2
	echo "  --test mode is for local testing" >&2
	echo "  --force mode is for production with monthly throttle bypass" >&2
	exit 1
fi

# Show force mode warning
if [ "$FORCE_RUN" = "true" ] && [ "$MODE" != "test" ]; then
	echo "⚠ Force mode enabled - bypassing monthly throttle check"
fi

# Set working directory based on mode. The `-m 700` applies to the leaf
# directory; parent dirs ($TMPDIR or $HOME) are pre-existing and not our
# concern, so SC2174's caveat doesn't apply here.
if [[ "$MODE" == test* ]]; then
	# Use tmpdir for test output to avoid hardcoding user paths
	TEST_OUTPUT_DIR="${TMPDIR:-/tmp}/sbom-test-${TIMESTAMP}"
	# shellcheck disable=SC2174
	mkdir -p -m 700 "$TEST_OUTPUT_DIR"
	SBOM_DIR="$TEST_OUTPUT_DIR"
else
	SBOM_DIR="${HOME}/.sbom-audit"
	# shellcheck disable=SC2174
	mkdir -p -m 700 "$SBOM_DIR"
fi

# === Helper Functions ===

check_already_run() {
	if [[ "$MODE" == test* ]] || [ "$FORCE_RUN" = "true" ]; then
		# Skip monthly check in test mode or when forced
		return 0
	fi

	# Check if we've already run this month
	local current_month
	current_month=$(date -u +%Y-%m)

	# Find any marker files from this month
	if find "$SBOM_DIR" -name ".last-upload-${current_month}*" -type f 2>/dev/null | grep -q .; then
		echo "✓ SBOM already uploaded this month ($current_month)"
		exit 0
	fi
}

# Set by detect_brew. Empty until a brew install is found.
BREW_BIN=""
# "workbrew" (MDM-managed, may run as root) or "homebrew" (refuses root).
BREW_FLAVOR=""

# Detect an existing brew installation and set BREW_BIN / BREW_FLAVOR / PATH
# explicitly. Returns 0 if found, 1 otherwise. Avoids `eval $(brew shellenv)`
# which would execute whatever the binary chose to emit — risky as root.
detect_brew() {
	local prefix=""
	if [ -x /opt/workbrew/bin/brew ]; then
		BREW_BIN="/opt/workbrew/bin/brew"
		BREW_FLAVOR="workbrew"
		prefix="/opt/workbrew"
	elif [ -x /opt/homebrew/bin/brew ]; then
		BREW_BIN="/opt/homebrew/bin/brew"
		BREW_FLAVOR="homebrew"
		prefix="/opt/homebrew"
	elif [ -x /usr/local/bin/brew ]; then
		BREW_BIN="/usr/local/bin/brew"
		BREW_FLAVOR="homebrew"
		prefix="/usr/local"
	else
		return 1
	fi

	export PATH="${prefix}/bin:${prefix}/sbin:${PATH}"
	export HOMEBREW_PREFIX="${prefix}"
	return 0
}

# Run a command in the user context that matches the active brew flavour.
# Workbrew is MDM-managed and accepts root; vanilla Homebrew refuses root,
# so drop to the logged-in console user via sudo when running as root. This
# applies not only to `brew` itself but to anything brew installs (pipx,
# python tools, etc.) — running them as their installer keeps the install
# and invocation in the same user context and avoids cross-user TOCTOU on
# Homebrew-managed binaries.
as_brew_user() {
	if [ "$(id -u)" -ne 0 ] || [ "$BREW_FLAVOR" = "workbrew" ]; then
		"$@"
		return $?
	fi

	# Homebrew + running as root. Drop to console user.
	if [ -z "${CONSOLE_USER:-}" ] || [ "$CONSOLE_USER" = "root" ]; then
		echo "✗ Cannot run a brew-managed tool as root without a console user." >&2
		echo "  This device should have Workbrew installed for MDM-managed use." >&2
		return 1
	fi
	sudo -u "$CONSOLE_USER" -H "$@"
}

# Invoke brew in the right user context. Wraps as_brew_user with the
# detected brew binary path.
brew_run() {
	if [ -z "$BREW_BIN" ]; then
		echo "✗ brew_run called before detect_brew succeeded" >&2
		return 1
	fi
	as_brew_user "$BREW_BIN" "$@"
}

ensure_homebrew() {
	# Prefer an existing installation. Workbrew is the MDM-managed brew
	# flavour and is expected to be pre-installed via the fleet config;
	# the script does not attempt to install Workbrew itself. If neither
	# is present, install Homebrew as a fallback so dependent packages
	# (jq, syft, etc.) can be installed.
	if detect_brew; then
		echo "✓ Using ${BREW_FLAVOR} at ${BREW_BIN}"
		return 0
	fi

	echo "✓ Neither Workbrew nor Homebrew found — installing Homebrew..."

	# Homebrew's installer refuses root. When running as root (MDM
	# MDM context), invoke the installer as the logged-in console user.
	if [ "$(id -u)" -eq 0 ]; then
		if [ -z "${CONSOLE_USER:-}" ] || [ "$CONSOLE_USER" = "root" ]; then
			echo "✗ Cannot install Homebrew as root with no console user." >&2
			echo "  Install Workbrew via MDM for managed devices, or" >&2
			echo "  install Homebrew manually for the device's primary user." >&2
			return 1
		fi
		if ! sudo -u "$CONSOLE_USER" -H /bin/bash -c '/bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"'; then
			echo "✗ Homebrew install failed (as $CONSOLE_USER)" >&2
			return 1
		fi
	else
		if ! /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"; then
			echo "✗ Homebrew install failed" >&2
			return 1
		fi
	fi

	if detect_brew; then
		echo "✓ Homebrew installed at ${BREW_BIN}"
		return 0
	fi

	echo "✗ Homebrew install reported success but no brew binary found" >&2
	return 1
}

ensure_jq() {
	if command -v jq &>/dev/null; then
		return 0
	fi

	echo "✓ Installing jq..."
	if [ -n "$BREW_BIN" ]; then
		brew_run install jq
		return $?
	fi

	echo "✗ jq is not installed and Homebrew is not available to install it" >&2
	return 1
}

ensure_gnumfmt() {
	# Check if numfmt is available (GNU coreutils)
	if command -v numfmt &>/dev/null; then
		return 0
	fi

	# On macOS, install GNU coreutils for gnumfmt
	if [[ "$(uname)" == "Darwin" ]]; then
		echo "✓ Installing GNU coreutils (for numfmt)..."
		if [ -n "$BREW_BIN" ]; then
			brew_run install coreutils
			return $?
		fi
	fi

	# Fall back to basic formatting if not available
	return 1
}

ensure_syft() {
	if [ -z "$BREW_BIN" ]; then
		if command -v syft &>/dev/null; then
			echo "  ⚠ Syft installed but brew not available for upgrades"
			return 0
		fi
		echo "✗ Syft is not installed and Homebrew is not available to install it" >&2
		return 1
	fi

	if command -v syft &>/dev/null; then
		echo "✓ Upgrading Syft..."
		# Don't mask failures — they may indicate tap compromise, network
		# issues, or a refuse-to-run-as-root response. Warn but continue
		# with the existing installed version rather than aborting the run.
		if ! brew_run upgrade syft; then
			echo "  ⚠ syft upgrade failed; continuing with existing version" >&2
		fi
		return 0
	fi

	echo "✓ Installing Syft..."
	brew_run install syft
	return $?
}

ensure_sbomnix() {
	if command -v sbomnix &>/dev/null; then
		return 0
	fi

	# Nix is required
	if ! command -v nix &>/dev/null; then
		echo "✗ Nix not available - required for sbomnix" >&2
		return 1
	fi

	echo "✓ Installing sbomnix..."
	nix profile add github:tiiuae/sbomnix --accept-flake-config || {
		echo "✗ sbomnix install failed" >&2
		return 1
	}

	# `nix profile add` installs into ~/.nix-profile/bin, but MDM runs
	# scripts non-interactively so /etc/profile.d/nix.sh is never sourced
	# and that directory is not on PATH. Without this step, the install
	# silently succeeds but the next `sbomnix` invocation falls into the
	# `|| continue` branch in generate_nix_sbom, producing an empty Nix
	# SBOM with no operator-visible error.
	local nix_bin
	for nix_bin in \
		"${HOME}/.nix-profile/bin" \
		"/nix/var/nix/profiles/per-user/$(id -un)/profile/bin" \
		"/nix/var/nix/profiles/default/bin"; do
		if [ -x "${nix_bin}/sbomnix" ]; then
			export PATH="${nix_bin}:${PATH}"
			break
		fi
	done

	if ! command -v sbomnix &>/dev/null; then
		echo "✗ sbomnix installed by 'nix profile add' but not found on PATH" >&2
		echo "  Searched: \$HOME/.nix-profile/bin, /nix/var/nix/profiles/per-user/\$(id -un)/profile/bin, /nix/var/nix/profiles/default/bin" >&2
		return 1
	fi
	return 0
}

ensure_pyspdxtools() {
	# pipx installs binaries into the user's ~/.local/bin. The "user" here
	# depends on the brew flavour: Workbrew runs as root → /var/root/.local/bin,
	# Homebrew runs as the console user → ${CONSOLE_USER_HOME}/.local/bin.
	# Resolve the correct path once.
	local pipx_bin
	if [ "$(id -u)" -eq 0 ] && [ "$BREW_FLAVOR" = "homebrew" ] && [ -n "${CONSOLE_USER:-}" ] && [ "$CONSOLE_USER" != "root" ]; then
		pipx_bin="${CONSOLE_USER_HOME}/.local/bin"
	else
		pipx_bin="${HOME}/.local/bin"
	fi

	if ! command -v pyspdxtools &>/dev/null && [ -x "${pipx_bin}/pyspdxtools" ]; then
		export PATH="${pipx_bin}:${PATH}"
	fi

	if command -v pyspdxtools &>/dev/null; then
		return 0
	fi

	echo "✓ Installing pyspdxtools (SPDX validator)..."
	if [ -n "$BREW_BIN" ]; then
		# Both steps run in the same user context as the brew that installs
		# pipx — keeps the install and invocation in one user and avoids
		# cross-user TOCTOU on the Homebrew-installed pipx binary.
		if ! brew_run install pipx; then
			echo "✗ pipx install via brew failed" >&2
			return 1
		fi
		if ! as_brew_user pipx install spdx-tools; then
			echo "✗ pipx install spdx-tools failed" >&2
			return 1
		fi
		if [ -x "${pipx_bin}/pyspdxtools" ]; then
			export PATH="${pipx_bin}:${PATH}"
			return 0
		fi
	fi

	return 1
}

validate_spdx() {
	local spdx_file="$1"

	if ! command -v pyspdxtools &>/dev/null; then
		echo "  ✗ pyspdxtools not available - cannot validate" >&2
		return 1
	fi

	echo "→ Validating SPDX document..."

	local validation_output
	validation_output=$(pyspdxtools -i "$spdx_file" 2>&1)
	local exit_code=$?

	if [ $exit_code -eq 0 ]; then
		echo "  ✓ SPDX validation passed"
		return 0
	else
		echo "  ✗ SPDX validation failed" >&2
		echo "$validation_output" | tail -20 >&2
		return 1
	fi
}

generate_nix_sbom() {
	# Ensure sbomnix is available (required)
	ensure_sbomnix || {
		echo "✗ sbomnix is required but not available" >&2
		return 1
	}

	local output_file="$1"
	local nix_sboms=()

	echo "→ Scanning Nix packages..."

	# Scan user profile packages (from nix profile list)
	if command -v nix &>/dev/null && [ -e "${CONSOLE_USER_HOME}/.nix-profile" ]; then
		echo "  → Scanning Nix profile packages..."

		# Get store paths from profile
		# When running as root (via MDM/sudo), query the console user's profile
		local store_paths
		if [ "$(id -u)" -eq 0 ] && [ -n "${CONSOLE_USER:-}" ] && [ "$CONSOLE_USER" != "root" ]; then
			store_paths=$(sudo -u "$CONSOLE_USER" nix profile list 2>/dev/null | grep "Store paths:" | awk '{print $3}')
		else
			store_paths=$(nix profile list 2>/dev/null | grep "Store paths:" | awk '{print $3}')
		fi

		if [ -z "$store_paths" ]; then
			echo "  ✗ No Nix store paths found in profile (nix profile list output may have changed)" >&2
			echo "  → Skipping Nix package scan (non-fatal)" >&2
		fi

		if [ -n "$store_paths" ]; then
			local path_count=0
			while IFS= read -r store_path; do
				if [ -n "$store_path" ] && [ -e "$store_path" ]; then
					local pkg_name
					pkg_name=$(basename "$store_path" | cut -d'-' -f2-)
					echo "    → Scanning: $pkg_name"

					local pkg_sbom="${SBOM_DIR}/nix-pkg-${path_count}-${TIMESTAMP}.spdx.json"

					# Run sbomnix in SBOM_DIR to contain output files
					(cd "$SBOM_DIR" && sbomnix "$store_path" --spdx "$pkg_sbom" 2>/dev/null) || {
						safe_delete_file "$pkg_sbom"
						continue
					}

					# Validate sbomnix produced valid SPDX output
					if [ -f "$pkg_sbom" ] && jq -e '.spdxVersion' "$pkg_sbom" >/dev/null 2>&1; then
						nix_sboms+=("$pkg_sbom")
						# Clean up extra outputs sbomnix creates
						safe_delete_file "${SBOM_DIR}/sbom.cdx.json"
						safe_delete_file "${SBOM_DIR}/sbom.csv"
						safe_delete_file "${SBOM_DIR}/http_cache.sqlite"
						path_count=$((path_count + 1))
					else
						echo "    ⚠ sbomnix produced invalid SPDX for $pkg_name (skipping)" >&2
						safe_delete_file "$pkg_sbom"
					fi
				fi
			done <<<"$store_paths"

			if [ $path_count -gt 0 ]; then
				echo "  ✓ Scanned $path_count profile package(s)"
			else
				echo "  ⚠ No profile packages could be scanned"
			fi
		else
			echo "  ⚠ No packages in profile"
		fi
	fi

	# If we have Nix SBOMs, merge them
	if [ ${#nix_sboms[@]} -gt 0 ]; then
		echo "  → Merging ${#nix_sboms[@]} Nix SBOM(s)..."

		# Merge packages from all Nix SBOMs, deduplicate licenses, remove CPE refs
		if ! jq -s '{
                SPDXID: "SPDXRef-DOCUMENT",
                spdxVersion: "SPDX-2.3",
                creationInfo: (.[0].creationInfo // {created: (now | strftime("%Y-%m-%dT%H:%M:%SZ"))}),
                name: (.[0].name // "nix-packages"),
                dataLicense: "CC0-1.0",
                documentNamespace: (.[0].documentNamespace // ""),
                hasExtractedLicensingInfos: (
                    [.[].hasExtractedLicensingInfos[]?] |
                    group_by(.licenseId) | map(.[0])
                ),
                packages: ([.[].packages[]?] | unique_by(.SPDXID // (.name + "-" + (.versionInfo // "UNKNOWN") + "-" + (.downloadLocation // "UNKNOWN"))) | 
                           map(
                               .filesAnalyzed = false |
                               del(.licenseInfoFromFiles, .packageVerificationCode, .hasFiles) |
                               if .versionInfo == "" then del(.versionInfo) else . end |
                               if .externalRefs then
                                   .externalRefs |= map(select(.referenceType != "cpe23Type"))
                               else . end |
                               if .externalRefs == [] then del(.externalRefs) else . end
                           ))
            } | if .hasExtractedLicensingInfos == [] then del(.hasExtractedLicensingInfos) else . end
        ' "${nix_sboms[@]}" >"$output_file"; then
			echo "  ✗ jq merge failed for Nix SBOMs" >&2
			return 1
		fi

		if [ ! -s "$output_file" ]; then
			echo "  ✗ jq produced empty output for Nix SBOMs" >&2
			return 1
		fi

		local pkg_count
		pkg_count=$(jq '.packages | length' "$output_file" 2>/dev/null || echo "0")
		echo "  ✓ Merged Nix SBOM: $pkg_count packages"

		if [[ "$MODE" == test* ]]; then
			echo "  ✓ Saved to: $output_file"
		fi

		return 0
	else
		# No Nix packages found, but sbomnix ran successfully
		# Create empty SBOM to satisfy the requirement
		echo "  ⚠ No Nix packages found (profile and projects empty)"
		echo '{"SPDXID":"SPDXRef-DOCUMENT","spdxVersion":"SPDX-2.3","name":"nix-packages","dataLicense":"CC0-1.0","documentNamespace":"http://spdx.org/spdxdocs/empty","packages":[],"relationships":[]}' >"$output_file"
		return 0
	fi
}

generate_system_sbom() {
	local output_file="$1"
	local temp_file="${output_file}.tmp"

	# Determine scan paths based on mode
	# Use inclusive scan: target specific package manager directories instead of
	# scanning all of / with exclusions. Scanning / is too slow — Syft indexes the
	# entire filesystem before applying excludes, so it walks through every dev
	# project, node_modules, vendor dir, etc.
	local scan_paths=()
	if [[ "$MODE" == test* ]]; then
