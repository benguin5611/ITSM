		[ -d "${CONSOLE_USER_HOME}/.hex" ] && scan_paths+=("${CONSOLE_USER_HOME}/.hex")
		[ -d "${CONSOLE_USER_HOME}/.mix" ] && scan_paths+=("${CONSOLE_USER_HOME}/.mix")

