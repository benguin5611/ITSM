		[ -d "${CONSOLE_USER_HOME}/.conan" ] && scan_paths+=("${CONSOLE_USER_HOME}/.conan")
		[ -d "${CONSOLE_USER_HOME}/.conan2" ] && scan_paths+=("${CONSOLE_USER_HOME}/.conan2")

