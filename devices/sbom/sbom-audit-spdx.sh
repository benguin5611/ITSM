  sbom-audit-spdx --force            # Force production run (bypass monthly check)
  sbom-audit-spdx clean INPUT OUT    # Clean SPDX file (utility)
  sbom-audit-spdx --help             # Show this help

Production Mode:
  - Checks if already run this month (exits if yes)
  - Scans Nix packages (sbomnix) and system packages (Syft)
  - Targets package manager directories (Homebrew, MacPorts, /usr/local)
  - Merges and deduplicates packages
  - Uploads to Lambda via presigned S3 URL
  - Creates monthly marker file

