		# Kotlin (kotlin-native, kscript cache)
		[ -d "${CONSOLE_USER_HOME}/.kotlin" ] && scan_paths+=("${CONSOLE_USER_HOME}/.kotlin")

		# Juliaup / Julia packages
		[ -d "${CONSOLE_USER_HOME}/.julia" ] && scan_paths+=("${CONSOLE_USER_HOME}/.julia")

