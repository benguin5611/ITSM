		[ -d "${CONSOLE_USER_HOME}/perl5" ] && scan_paths+=("${CONSOLE_USER_HOME}/perl5")

		# Groovy / Grape
		[ -d "${CONSOLE_USER_HOME}/.groovy/grapes" ] && scan_paths+=("${CONSOLE_USER_HOME}/.groovy/grapes")

