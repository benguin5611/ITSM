#!/usr/bin/env bash
# SPDX SBOM Collection Script for Device Inventory
# Supports production mode (upload to Lambda) and test mode (local output)
#
# Usage:
#   sbom-audit-spdx                    # Production mode (monthly upload to Lambda)
#   sbom-audit-spdx --test             # Test mode (local output)
#   sbom-audit-spdx clean INPUT OUT    # Clean SPDX file for conversion
#   sbom-audit-spdx --help             # Show help

set -euo pipefail

# === Configuration ===
# Lambda URL - must be set via SBOM_LAMBDA_URL environment variable
LAMBDA_URL="${SBOM_LAMBDA_URL:-}"

# Device ID (from hostname, sanitized to prevent header injection / path traversal)
DEVICE_ID="${HOSTNAME:-$(hostname)}"
DEVICE_ID="${DEVICE_ID//[^a-zA-Z0-9._-]/}"
if [ -z "$DEVICE_ID" ]; then
	echo "✗ Could not determine a valid device ID from hostname" >&2
	exit 1
fi

# Timestamp for filenames
TIMESTAMP=$(date -u +%Y%m%d-%H%M%S)

# Detect primary macOS user (for Nix profile scanning when running as root via MDM)
if [ "$(id -u)" -eq 0 ]; then
	CONSOLE_USER=$(stat -f '%Su' /dev/console 2>/dev/null || echo "")
	if [ -n "$CONSOLE_USER" ] && [ "$CONSOLE_USER" != "root" ]; then
		CONSOLE_USER_HOME=$(dscl . -read "/Users/$CONSOLE_USER" NFSHomeDirectory 2>/dev/null | awk '{print $2}')
	else
		CONSOLE_USER_HOME="$HOME"
	fi
else
	CONSOLE_USER_HOME="$HOME"
fi

# === Mode Detection ===
MODE="production"
TEST_OUTPUT_DIR=""
FORCE_RUN="false"

# Strict deletion guardrail function
safe_delete_file() {
	local file_path="$1"

	# Verify file exists and is a regular file
	if [ ! -f "$file_path" ]; then
		return 0
	fi

	# Verify file is within SBOM_DIR
	local file_dir
	file_dir=$(dirname "$(realpath "$file_path" 2>/dev/null || echo "$file_path")")
	local sbom_realpath
	sbom_realpath=$(realpath "$SBOM_DIR" 2>/dev/null || echo "$SBOM_DIR")

	# Must be exactly SBOM_DIR or a subdirectory (not just prefix match)
	if [[ "$file_dir" != "$sbom_realpath" && "$file_dir" != "$sbom_realpath"/* ]]; then
		echo "✗ SAFETY: Refusing to delete file outside SBOM_DIR: $file_path" >&2
		return 1
	fi

	# Only delete files matching our patterns
	local basename
	basename=$(basename "$file_path")
	# Whitelist the exact filename patterns we create. The trailing
	# `(\.tmp\.[0-9]+)?` covers the partial-SBOM temp files generated by
	# generate_system_sbom; everything else must match exactly.
	if [[ "$basename" =~ ^(nix-.*\.spdx\.json|system-.*\.spdx\.json(\.tmp\.[0-9]+)?|device-.*\.spdx\.json|nix-pkg-[0-9]+-.*\.spdx\.json|sbom\.(cdx\.json|csv)|http_cache\.sqlite)$ ]]; then
		rm -f "$file_path"
		return 0
	else
		echo "✗ SAFETY: Refusing to delete unrecognized file pattern: $file_path" >&2
		return 1
	fi
}

format_bytes() {
	local bytes="$1"
	if command -v numfmt &>/dev/null; then
		numfmt --to=iec-i --suffix=B "$bytes" 2>/dev/null
	elif command -v gnumfmt &>/dev/null; then
		gnumfmt --to=iec-i --suffix=B "$bytes" 2>/dev/null
	else
		echo "${bytes} bytes"
	fi
}

# Handle subcommands first
if [ "${1:-}" = "clean" ]; then
	if [ $# -ne 3 ]; then
		echo "Usage: $0 clean <input.spdx.json> <output.spdx.json>" >&2
		exit 1
	fi

	CLEAN_INPUT="$2"
	CLEAN_OUTPUT="$3"

	echo "=== SPDX Cleanup Utility ==="
	echo "Input:  $CLEAN_INPUT"
	echo "Output: $CLEAN_OUTPUT"
	echo ""

	if [ ! -f "$CLEAN_INPUT" ]; then
		echo "✗ Input file not found: $CLEAN_INPUT" >&2
		exit 1
	fi

	# Use temporary file for atomic writes (prevents partial output on disk full)
	tmp_out="${CLEAN_OUTPUT}.tmp.$$"
	trap 'rm -f "$tmp_out"' EXIT INT TERM

	echo "Cleaning SPDX document..."
	echo "  - Removing files[] and cleaning dangling file references"
	echo "  - Deduplicating hasExtractedLicensingInfos[]"
	echo "  - Adding filesAnalyzed: false to packages"
	echo "  - Removing file-dependent fields (licenseInfoFromFiles, packageVerificationCode, hasFiles)"
	echo "  - Removing empty versionInfo fields"
	echo "  - Removing CPE externalRefs (cpe23Type)"
	jq '
        # Capture file SPDX IDs before deleting files
        ([.files[]?.SPDXID] | map(select(. != null))) as $file_ids |
        del(.files) |
        # Remove relationships referencing deleted file elements
        if .relationships then
            .relationships |= map(select(
                (.spdxElementId | IN($file_ids[]) | not) and
                (.relatedSpdxElement | IN($file_ids[]) | not)
            ))
            | if .relationships == [] then del(.relationships) else . end
        else . end |
        # Remove documentDescribes entries referencing deleted file elements
        if .documentDescribes then
            .documentDescribes |= map(select(IN($file_ids[]) | not))
            | if .documentDescribes == [] then del(.documentDescribes) else . end
        else . end |
        # Deduplicate hasExtractedLicensingInfos (case-sensitive, no normalization)
        if .hasExtractedLicensingInfos then
            .hasExtractedLicensingInfos |= (group_by(.licenseId) | map(.[0]))
        else . end |
        # Clean packages
        if (.packages | type) == "array" then
            .packages |= map(
                .filesAnalyzed = false |
                del(.licenseInfoFromFiles, .packageVerificationCode, .hasFiles) |
                if .versionInfo == "" then del(.versionInfo) else . end |
                if .externalRefs then
                    .externalRefs |= map(select(.referenceType != "cpe23Type"))
                else . end |
                if .externalRefs == [] then del(.externalRefs) else . end
            )
        else . end' \
		"$CLEAN_INPUT" >"$tmp_out"

	# Atomic rename on success
	mv "$tmp_out" "$CLEAN_OUTPUT"

	ORIG_SIZE=$(wc -c <"$CLEAN_INPUT" | tr -d ' ')
	NEW_SIZE=$(wc -c <"$CLEAN_OUTPUT" | tr -d ' ')
	PKG_COUNT=$(jq '.packages | length' "$CLEAN_OUTPUT" 2>/dev/null || echo "0")
	LICENSE_COUNT=$(jq '.hasExtractedLicensingInfos | length' "$CLEAN_OUTPUT" 2>/dev/null || echo "0")

	ORIG_FMT=$(format_bytes "$ORIG_SIZE")
	NEW_FMT=$(format_bytes "$NEW_SIZE")

	echo "✓ Cleaned SPDX document"
	echo "  Original size: $ORIG_FMT"
	echo "  Cleaned size: $NEW_FMT"
	echo "  Packages: $PKG_COUNT"
	echo "  Licenses: $LICENSE_COUNT (deduplicated)"
	echo "  Removed: files[], licenseInfoFromFiles, packageVerificationCode, hasFiles, cpe23Type refs"
	echo ""
	echo "✓ Output saved to: $CLEAN_OUTPUT"
	exit 0
fi

# Handle flags (parse all arguments to detect conflicts)
for arg in "$@"; do
	case "$arg" in
	--test)
		MODE="test"
		;;
	--test-upload)
		MODE="test-upload"
		;;
	--force)
		FORCE_RUN="true"
		;;
	--help | -h)
		MODE="help"
		;;
	esac
done

# Handle help flag
if [ "$MODE" = "help" ]; then
	cat <<'EOF'
