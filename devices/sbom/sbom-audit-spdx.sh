		[ -d "${CONSOLE_USER_HOME}/miniconda3" ] && scan_paths+=("${CONSOLE_USER_HOME}/miniconda3")
		[ -d "${CONSOLE_USER_HOME}/anaconda3" ] && scan_paths+=("${CONSOLE_USER_HOME}/anaconda3")
