		[ -d "${CONSOLE_USER_HOME}/.local/share/mise" ] && scan_paths+=("${CONSOLE_USER_HOME}/.local/share/mise")

		# Volta (Node.js version manager + global packages)
		[ -d "${CONSOLE_USER_HOME}/.volta" ] && scan_paths+=("${CONSOLE_USER_HOME}/.volta")

		# fnm (fast Node.js version manager)
		[ -d "${CONSOLE_USER_HOME}/.local/share/fnm" ] && scan_paths+=("${CONSOLE_USER_HOME}/.local/share/fnm")
		[ -d "${CONSOLE_USER_HOME}/Library/Application Support/fnm" ] && scan_paths+=("${CONSOLE_USER_HOME}/Library/Application Support/fnm")

		# Deno (runtime + cached modules)
		[ -d "${CONSOLE_USER_HOME}/.deno" ] && scan_paths+=("${CONSOLE_USER_HOME}/.deno")

		# Bun (runtime + installed packages)
		[ -d "${CONSOLE_USER_HOME}/.bun" ] && scan_paths+=("${CONSOLE_USER_HOME}/.bun")

