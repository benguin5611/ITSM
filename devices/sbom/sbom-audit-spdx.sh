		[ -d "${CONSOLE_USER_HOME}/.composer" ] && scan_paths+=("${CONSOLE_USER_HOME}/.composer")

		# Haskell (ghcup, cabal, stack)
		[ -d "${CONSOLE_USER_HOME}/.ghcup" ] && scan_paths+=("${CONSOLE_USER_HOME}/.ghcup")
		[ -d "${CONSOLE_USER_HOME}/.cabal" ] && scan_paths+=("${CONSOLE_USER_HOME}/.cabal")
		[ -d "${CONSOLE_USER_HOME}/.stack" ] && scan_paths+=("${CONSOLE_USER_HOME}/.stack")

